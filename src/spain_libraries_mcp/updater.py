"""Generate data/municipalities.csv with municipalities of Catalonia and their official coordinates.

Source: "Caps de municipi de Catalunya georeferenciats" (Generalitat de Catalunya / ICGC),
https://analisi.transparenciacatalunya.cat/Sector-P-blic/Caps-de-municipi-de-Catalunya-georeferenciats/wpyq-we8x

Usage:
    spain-libraries-update-municipalities                      # download from Generalitat (requires internet)
    spain-libraries-update-municipalities --input data.csv     # from a pre-downloaded CSV
    spain-libraries-update-municipalities --output ~/municipalities.csv
    # then: export SPAIN_LIBRARIES_MUNICIPALITIES=~/municipalities.csv

Column names from the portal are detected by keywords and printed to stderr. If name or
coordinates cannot be found, the script exits with a clear error instead of writing a broken file.
"""

from __future__ import annotations

import argparse
import csv
import io
import sys
from pathlib import Path

from .geo import DATA, norm

URL = "https://analisi.transparenciacatalunya.cat/resource/wpyq-we8x.csv?$limit=5000"
PROVINCES = {"08": "Barcelona", "17": "Girona", "25": "Lleida", "43": "Tarragona"}


def _pick(headers: list[str], *, all_of: tuple[str, ...] = (), any_of: tuple[str, ...] = (),
          exclude: tuple[str, ...] = ()) -> str | None:
    for h in headers:
        n = norm(h).replace(" ", "_")
        if any(x in n for x in exclude):
            continue
        if all(t in n for t in all_of) and (not any_of or any(a in n for a in any_of)):
            return h
    return None


def detect_columns(headers: list[str]) -> dict[str, str | None]:
    return {
        "name": (_pick(headers, all_of=("nom", "municipi"), exclude=("comarca", "provincia"))
                 or _pick(headers, all_of=("municipi",), exclude=("codi", "comarca", "provincia", "ine"))
                 or _pick(headers, all_of=("nom",), exclude=("comarca", "provincia", "cap"))),
        "county": _pick(headers, all_of=("nom", "comarca")) or _pick(headers, all_of=("comarca",), exclude=("codi",)),
        "province": _pick(headers, all_of=("provincia",), exclude=("codi",)),
        "ine_code": _pick(headers, all_of=("ine",)),
        "lat": _pick(headers, any_of=("lat",), exclude=("utm", "xutm", "yutm")),
        "lon": _pick(headers, any_of=("lon", "long"), exclude=("utm", "xutm", "yutm")),
    }


def convert(csv_text: str) -> tuple[list[dict], dict[str, str | None]]:
    reader = csv.DictReader(io.StringIO(csv_text))
    cols = detect_columns(reader.fieldnames or [])
    missing = [k for k in ("name", "lat", "lon") if not cols[k]]
    if missing:
        raise SystemExit(f"Could not find columns {missing} in {reader.fieldnames}. "
                         "Check the input file or adjust `detect_columns()`.")
    rows = []
    for r in reader:
        try:
            lat, lon = float(r[cols["lat"]].replace(",", ".")), float(r[cols["lon"]].replace(",", "."))
        except (ValueError, AttributeError):
            continue
        ine = (r.get(cols["ine_code"]) or "").strip() if cols["ine_code"] else ""
        prov = (r.get(cols["province"]) or "").strip() if cols["province"] else ""
        rows.append({
            "name": r[cols["name"]].strip(),
            "province": prov or PROVINCES.get(ine[:2], ""),
            "county": (r.get(cols["county"]) or "").strip() if cols["county"] else "",
            "region": "cataluna",
            "lat": f"{lat:.5f}",
            "lon": f"{lon:.5f}",
            "approx": "0",
        })
    if not rows:
        raise SystemExit("The input file contains no rows with valid coordinates.")
    return rows, cols


def write_csv(rows: list[dict], output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    with open(output, "w", encoding="utf-8", newline="") as fh:
        fh.write("# Generated by spain-libraries-update-municipalities (Generalitat de Catalunya / ICGC).\n")
        w = csv.DictWriter(fh, fieldnames=["name", "province", "county", "region", "lat", "lon", "approx"])
        w.writeheader()
        w.writerows(sorted(rows, key=lambda f: norm(f["name"])))


def main() -> None:
    p = argparse.ArgumentParser(description="Update the list of municipalities with coordinates")
    p.add_argument("--input", type=Path, help="Pre-downloaded CSV (otherwise downloaded from Generalitat)")
    p.add_argument("--output", type=Path, default=DATA / "municipalities.csv")
    a = p.parse_args()
    if a.input:
        text = a.input.read_text(encoding="utf-8-sig")
    else:
        import httpx
        r = httpx.get(URL, timeout=60, follow_redirects=True, headers={"User-Agent": "spain-libraries-mcp"})
        r.raise_for_status()
        text = r.text
    rows, cols = convert(text)
    write_csv(rows, a.output)
    print(f"Wrote {len(rows)} municipalities to {a.output}", file=sys.stderr)
    print("Columns used: " + ", ".join(f"{k}={v}" for k, v in cols.items()), file=sys.stderr)


if __name__ == "__main__":
    main()
